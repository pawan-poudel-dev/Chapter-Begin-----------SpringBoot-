package com.aidesktopagent.coding;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Objects;

/**
 * Generates a minimal Maven Java project from a controlled template (Day 25).
 * Only writes inside the parent workspace when constrained.
 */
public final class ProjectGenerator {

    private final Path parentDir;

    public ProjectGenerator(Path parentDir) {
        this.parentDir = Objects.requireNonNull(parentDir).toAbsolutePath().normalize();
    }

    public Path generate(String artifactId, String packageName) throws IOException {
        if (artifactId == null || !artifactId.matches("[a-zA-Z][\\w-]{0,40}")) {
            throw new IllegalArgumentException("Invalid artifactId");
        }
        if (packageName == null || !packageName.matches("[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)*")) {
            throw new IllegalArgumentException("Invalid package name");
        }
        Path root = parentDir.resolve(artifactId);
        if (Files.exists(root)) {
            throw new IOException("Directory already exists: " + root);
        }
        Path main = root.resolve("src/main/java/" + packageName.replace('.', '/'));
        Path test = root.resolve("src/test/java/" + packageName.replace('.', '/'));
        Files.createDirectories(main);
        Files.createDirectories(test);

        String pom = """
                <?xml version="1.0" encoding="UTF-8"?>
                <project xmlns="http://maven.apache.org/POM/4.0.0"
                         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
                         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
                  <modelVersion>4.0.0</modelVersion>
                  <groupId>com.example</groupId>
                  <artifactId>%s</artifactId>
                  <version>0.1.0-SNAPSHOT</version>
                  <properties>
                    <maven.compiler.release>17</maven.compiler.release>
                    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
                  </properties>
                  <dependencies>
                    <dependency>
                      <groupId>org.junit.jupiter</groupId>
                      <artifactId>junit-jupiter</artifactId>
                      <version>5.11.3</version>
                      <scope>test</scope>
                    </dependency>
                  </dependencies>
                  <build>
                    <plugins>
                      <plugin>
                        <groupId>org.apache.maven.plugins</groupId>
                        <artifactId>maven-surefire-plugin</artifactId>
                        <version>3.5.2</version>
                      </plugin>
                    </plugins>
                  </build>
                </project>
                """.formatted(artifactId);
        Files.writeString(root.resolve("pom.xml"), pom);

        String className = toClassName(artifactId);
        Files.writeString(main.resolve(className + ".java"), """
                package %s;
                
                public final class %s {
                    public String hello() {
                        return "hello";
                    }
                
                    public static void main(String[] args) {
                        System.out.println(new %s().hello());
                    }
                }
                """.formatted(packageName, className, className));

        Files.writeString(test.resolve(className + "Test.java"), """
                package %s;
                
                import org.junit.jupiter.api.Test;
                import static org.junit.jupiter.api.Assertions.*;
                
                class %sTest {
                    @Test
                    void hello() {
                        assertEquals("hello", new %s().hello());
                    }
                }
                """.formatted(packageName, className, className));

        Files.writeString(root.resolve("README.md"), "# " + artifactId + "\n\nGenerated by AI Desktop Agent.\n");
        return root;
    }

    private static String toClassName(String artifactId) {
        StringBuilder sb = new StringBuilder();
        for (String part : artifactId.split("[-_]")) {
            if (part.isEmpty()) continue;
            sb.append(Character.toUpperCase(part.charAt(0)));
            if (part.length() > 1) sb.append(part.substring(1));
        }
        return sb.isEmpty() ? "App" : sb.toString();
    }
}
